class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('ao_site_lang') || 'es';
    if (!['es', 'pt', 'en'].includes(this.currentLang)) {
      this.currentLang = 'es';
    }
  }

  init() {
    this.applyLanguage(this.currentLang);
    this.setupListeners();
  }

  setLanguage(lang) {
    if (translations[lang]) {
      this.currentLang = lang;
      localStorage.setItem('ao_site_lang', lang);
      this.applyLanguage(lang);
      window.dispatchEvent(new CustomEvent('ao:languageChanged', { detail: { lang } }));
    }
  }

  applyLanguage(lang) {
    document.documentElement.lang = lang;
    const dict = translations[lang] || translations.es;
    
    // Update elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = dict[key];
        } else {
          el.innerHTML = dict[key];
        }
      }
    });

    // Update language selector UI
    const select = document.getElementById('langSelector');
    if (select && select.value !== lang) {
      select.value = lang;
    }
  }

  setupListeners() {
    const select = document.getElementById('langSelector');
    if (select) {
      select.addEventListener('change', (e) => {
        this.setLanguage(e.target.value);
      });
    }
  }

  t(key) {
    const dict = translations[this.currentLang] || translations.es;
    return dict[key] || key;
  }
}

export const i18n = new I18nManager();
